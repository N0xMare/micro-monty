#!/usr/bin/env python3
"""Compares Python on micro-monty (py-ptc, mm-cell-worker) with JavaScript on
plak's QuickJS worker (js-ptc, plakous-js-host) per model, from the census
records of the JS-vs-Python study (docs/research/js-vs-python-models.md).

    python3 jsvpy.py results/js-vs-python   # reads cells, sessions, grade.jsonl

Engine time is `engine_ms_calls` (census.py): wall time minus the time a
nested call was outstanding, the one measure both workers' frames support.
Memory is each session's worker peak RSS (VmHWM).
"""

import builtins
import json
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ARMS = ["codex-ptc-mm", "codex-jsptc-qjs", "grok-ptc-mm", "grok-jsptc-qjs"]
GROUPS = ["model: other language", "model: syntax error", "model: runtime error",
          "missing feature", "refusal by design", "tool error", "terminated or cut off"]


def group(cell):
    """The study's four causes (model, missing feature, refusal, tool error),
    with model mistakes split, and cells with no `cell_done` (terminated by the
    model, or cut off by the session timeout) apart."""
    cls, cause = cell["class"], cell["cause"]
    if cell["outcome"] in ("unfinished", "stopped", "lost"):
        return "terminated or cut off"
    if cls in ("model: JavaScript", "model: Python"):
        return "model: other language"
    if cls == "model: syntax error":
        return "model: syntax error"
    # No ambient filesystem or processes, globals() read-only (spec §4, G2), no Node APIs.
    if cls == "sandbox: no Node API" or "sandbox" in cause.lower() or "read-only view" in cause:
        return "refusal by design"
    undefined = re.match(r"NameError: name '(\w+)' is not defined", cause)
    if cls == "engine: refusal or gap" or (undefined and hasattr(builtins, undefined.group(1))):
        return "missing feature"
    if cls == "host: tool error":
        return "tool error"
    return "model: runtime error"


def med(values):
    values = [v for v in values if v is not None]
    return statistics.median(values) if values else None


def p90(values):
    values = sorted(v for v in values if v is not None)
    return values[int(0.9 * (len(values) - 1))] if values else None


def num(value, digits=0):
    if value is None:
        return "–"
    return f"{value:,.{digits}f}"


def main():
    out = Path(sys.argv[1])
    cells = [json.loads(l) for l in (out / "cells.jsonl").open()]
    sessions = [json.loads(l) for l in (out / "sessions.jsonl").open()]
    grades = {(g["arm"], g["prompt"]): g["correct"]
              for g in map(json.loads, (out / "grade.jsonl").open())}
    by_arm = defaultdict(list)
    for cell in cells:
        by_arm[cell["arm"]].append(cell)
    lines = ["# JS on QuickJS vs Python on micro-monty: per-arm table", "",
             "Generated by `jsvpy.py` from `cells.jsonl`, `sessions.jsonl` and `grade.jsonl`.", ""]
    lines += ["| arm | sessions | answered | timed out | correct (todo, loc) | model turns (median, total) "
              "| input tokens (median) | output tokens (median) | cells (median, total) | failed cells "
              "| median engine ms | p90 engine ms | median worker CPU ms | median cell wall ms "
              "| median session s | median worker peak RSS KiB |",
              "|---|" + "---:|" * 15]
    for arm in ARMS:
        ss = [s for s in sessions if s["arm"] == arm]
        cs = by_arm[arm]
        if not ss:
            continue
        answered = sum(s["exit"] == 0 and s["answer_chars"] > 0 for s in ss)
        timed_out = sum(s["exit"] != 0 for s in ss)
        graded = [grades[(arm, p)] for p in ("todo-census", "loc-census") if (arm, p) in grades]
        lines.append(
            f"| {arm} | {len(ss)} | {answered} | {timed_out} | {sum(graded)} of {len(graded)} | "
            f"{num(med([s.get('model_operations') for s in ss]))}, "
            f"{num(sum(s.get('model_operations') or 0 for s in ss))} | "
            f"{num(med([s.get('input_tokens') for s in ss]))} | "
            f"{num(med([s.get('output_tokens') for s in ss]))} | "
            f"{num(med([s['cells'] for s in ss]), 1)}, {len(cs)} | "
            f"{sum(c['outcome'] != 'completed' for c in cs)} | "
            f"{num(med([c['engine_ms_calls'] for c in cs]), 2)} | "
            f"{num(p90([c['engine_ms_calls'] for c in cs]), 2)} | "
            f"{num(med([c.get('cpu_ms') for c in cs]), 2)} | "
            f"{num(med([c['wall_ms'] for c in cs]), 1)} | "
            f"{num(med([s['wall_s'] for s in ss]), 1)} | "
            f"{num(med([s['worker_peak_rss_kb'] for s in ss]))} |")
    lines += ["", "## Failed cells by cause", "", "| arm | " + " | ".join(GROUPS) + " |",
              "|---|" + "---:|" * len(GROUPS)]
    for arm in ARMS:
        counts = Counter(group(c) for c in by_arm[arm] if c["class"])
        lines.append(f"| {arm} | " + " | ".join(str(counts[g]) for g in GROUPS) + " |")
    lines += ["", "## Failed cells by census class", "", "| arm | class | cells |", "|---|---|---:|"]
    for (arm, cls), n in sorted(Counter((c["arm"], c["class"]) for c in cells if c["class"]).items(),
                                key=lambda item: (ARMS.index(item[0][0]), -item[1])):
        lines.append(f"| {arm} | {cls} | {n} |")
    lines += ["", "## Cells per prompt", "", "| prompt | " + " | ".join(ARMS) + " |",
              "|---|" + "---:|" * len(ARMS)]
    for prompt in dict.fromkeys(s["prompt"] for s in sessions):
        row = []
        for arm in ARMS:
            s = next((s for s in sessions if s["arm"] == arm and s["prompt"] == prompt), None)
            row.append("–" if s is None else f"{s['cells']} ({s['failed_cells']} failed)")
        lines.append(f"| {prompt} | " + " | ".join(row) + " |")
    lines.append("")
    (out / "compare.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
