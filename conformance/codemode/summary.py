"""Renders results/summary.md from the run records of run.py."""

from __future__ import annotations

import collections

ENGINES = ('cpython', 'mm-default', 'mm-full')
# Modules the survey (docs/research/codemode-survey.md §7 R-T) asks about by name.
WATCH = ('statistics', 'tomllib', 'uuid', 'decimal', 'unicodedata', 'fractions', 'struct', 'html', 'platform',
         'difflib', 'pprint', 'logging', 'codecs', 'traceback', 'warnings', 'gc', 'zoneinfo', 'typing_extensions')
# Solution authors by set (README "How the solutions were written", "Second model family").
FAMILIES = ('claude', 'gpt-6-luna', 'gpt-6.1-sol')


def family(set_name: str) -> str:
    return {'luna': 'gpt-6-luna', 'sol': 'gpt-6.1-sol'}.get(set_name.split('-')[0], 'claude')


def _pct(n: int, d: int) -> str:
    return f'{n / d * 100:.1f}%' if d else '-'


def _waiting(r: dict) -> int:
    # Over both builds: a solution that fails early on one build (an import) never fans out there.
    return max(r[e].get('max_waiting') or 0 for e in ENGINES[1:])


def render(records: list[dict], shas: dict[str, str]) -> str:
    from run import tier  # noqa: PLC0415

    probes = [r for r in records if r['set'] == 'p']
    records = [r for r in records if r['set'] != 'p']
    fams = {f: [r for r in records if family(r['set']) == f] for f in FAMILIES}
    fams = {f: rs for f, rs in fams.items() if rs}
    ok = [r for r in records if r['cpython']['outcome'] == 'pass']
    n = len(records)
    out = ['# codemode results', '', 'Generated by `run.py`; see README.md for the method.', '']
    out += ['## Totals', '']
    by_set = collections.Counter(r['set'] for r in records)
    sets = ', '.join(f'{s}: {c}' for s, c in sorted(by_set.items()))
    out.append(f'{n} solutions ({sets}), {len({r["task"] for r in records})} tasks. Families: '
               + ', '.join(f'{f} ({len(rs)})' for f, rs in fams.items()) + '.')
    out.append('')
    out.append('| set | solutions | CPython pass | mm-default pass (of CPython pass) | mm-full pass (of CPython pass) |')
    out.append('|---|---:|---:|---:|---:|')
    groups = [(s, [r for r in records if r['set'] == s]) for s in sorted(by_set)]
    groups += [(f'**{f}**', rs) for f, rs in fams.items()] + [('**all**', records)]
    for label, rs in groups:
        okr = [r for r in rs if r['cpython']['outcome'] == 'pass']
        cells = [label, str(len(rs)), f'{len(okr)} ({_pct(len(okr), len(rs))})']
        for e in ENGINES[1:]:
            p = sum(r[e]['outcome'] == 'pass' for r in okr)
            cells.append(f'{p} ({_pct(p, len(okr))})')
        out.append('| ' + ' | '.join(cells) + ' |')
    out.append('')
    out.append('Binary SHA-256: ' + ', '.join(f'`{c}` {h}' for c, h in sorted(shas.items())))
    out.append('')

    for e in ENGINES[1:]:
        out += [f'## {e}: failure causes on CPython-passing solutions', '']
        causes = collections.Counter(r[e]['cause'] for r in ok if r[e]['outcome'] != 'pass')
        out.append('| cause | ' + ' | '.join(fams) + ' | all | example |')
        out.append('|---|' + '---:|' * (len(fams) + 1) + '---|')
        for c, k in causes.most_common():
            per = [sum(1 for r in rs if r['cpython']['outcome'] == 'pass' and r[e]['outcome'] != 'pass'
                       and r[e]['cause'] == c) for rs in fams.values()]
            ex = next(r for r in ok if r[e].get('cause') == c)
            out.append(f'| {c} | ' + ' | '.join(map(str, per)) + f' | {k} | {ex["set"]}/{ex["task"]} |')
        out.append('')
        passing = [r for r in ok if r[e]['outcome'] == 'pass']
        same = sum(r[e].get('same_calls', False) for r in passing)
        out.append(f'Passing solutions with the same tool calls as CPython, batch by batch (README "Same calls"): {same} of {len(passing)}.')
        out.append('')

    bad = [r for r in records if r['cpython']['outcome'] != 'pass']
    out += ['## Solutions that fail on CPython (task or solution errors)', '']
    out.append('| solution | outcome | cause |')
    out.append('|---|---|---|')
    for r in bad:
        out.append(f'| {r["set"]}/{r["task"]} | {r["cpython"]["outcome"]} | {r["cpython"].get("cause")} |')
    out.append('')

    out += ['## Imports (share of each family\'s solutions)', '']
    mods = collections.Counter(m for r in records for m in set(r['imports']))
    out.append('| module | tier | ' + ' | '.join(fams) + ' | all | CPython-passing, failing on mm-default (any cause) |')
    out.append('|---|---|' + '---:|' * (len(fams) + 2))
    for m, k in sorted(mods.items(), key=lambda x: (-x[1], x[0])):
        per = [_pct(sum(1 for r in rs if m in r['imports']), len(rs)) for rs in fams.values()]
        fails = sum(1 for r in ok if m in r['imports'] and r['mm-default']['outcome'] != 'pass')
        out.append(f'| {m} | {tier(m)} | ' + ' | '.join(per) + f' | {k} ({_pct(k, n)}) | {fails} |')
    out.append('')
    out += ['### Watched modules (survey R-T)', '']
    out.append('| module | ' + ' | '.join(fams) + ' |')
    out.append('|---|' + '---:|' * len(fams))
    for m in WATCH:
        per = [sum(1 for r in rs if any(i == m or i.startswith(m + '.') for i in r['imports'])) for rs in fams.values()]
        out.append(f'| {m} | ' + ' | '.join(map(str, per)) + ' |')
    out.append('')
    out += ['### from-import and attribute names (top 80)', '']
    attrs = collections.Counter(a for r in records for a in set(r['attrs']))
    out.append(', '.join(f'`{a}` {k}' for a, k in attrs.most_common(80)))
    out.append('')

    out += ['## Builtins and features', '']
    for key in ('builtins', 'features'):
        cnt = collections.Counter(b for r in records for b in set(r[key]))
        out.append(f'**{key}**: ' + ', '.join(f'`{b}` {k}' for b, k in cnt.most_common()))
        out.append('')

    out += ['## String vs structured results', '']
    out.append('| family | mode | solutions | CPython pass | mm-default pass of CPython pass | mm-full pass of CPython pass |')
    out.append('|---|---|---:|---:|---:|---:|')
    for f, frs in [*fams.items(), ('all', records)]:
        for mode in ('string', 'structured'):
            rs = [r for r in frs if r['mode'] == mode]
            okm = [r for r in rs if r['cpython']['outcome'] == 'pass']
            p = [sum(r[e]['outcome'] == 'pass' for r in okm) for e in ENGINES[1:]]
            out.append(f'| {f} | {mode} | {len(rs)} | {len(okm)} ({_pct(len(okm), len(rs))}) | '
                       f'{p[0]} ({_pct(p[0], len(okm))}) | {p[1]} ({_pct(p[1], len(okm))}) |')
    out.append('')

    out += ['## Concurrency and output size', '']
    out.append('Most host futures outstanding in one wait, per solution (the larger of the two mm builds):')
    out.append('')
    out.append('| family | 0-1 | 2-16 | more than 16 | above 16 |')
    out.append('|---|---:|---:|---:|---|')
    for f, rs in fams.items():
        w = collections.Counter('>16' if _waiting(r) > 16 else '2-16' if _waiting(r) > 1 else '0-1' for r in rs)
        over = ', '.join(f'{r["set"]}/{r["task"]} {_waiting(r)}' for r in rs if _waiting(r) > 16)
        out.append(f'| {f} | {w["0-1"]} | {w["2-16"]} | {w[">16"]} | {over} |')
    out.append('')
    out.append('| family | largest stdout | above 16 KiB |')
    out.append('|---|---|---|')
    for f, rs in fams.items():
        big = max(rs, key=lambda r: r['cpython'].get('stdout_bytes', 0))
        over = [f'{r["set"]}/{r["task"]}' for r in rs if r['cpython'].get('stdout_bytes', 0) > 16384]
        out.append(f'| {f} | {big["cpython"].get("stdout_bytes")} bytes ({big["set"]}/{big["task"]}) | '
                   f'{len(over)}: {", ".join(over)} |')
    out.append('')

    out += ['## Probes (hand-written, not in the census)', '']
    out.append('| probe | CPython | mm-default |')
    out.append('|---|---|---|')
    for r in probes:
        cells = []
        for e in ('cpython', 'mm-default'):
            x = r[e]
            err = x.get('error')
            cells.append(f"{err['type']}: {err['message']}" if err else x['outcome'])
        out.append(f"| {r['task']} | {cells[0].replace('|', '/')} | {cells[1].replace('|', '/')} |")
    out.append('')
    return '\n'.join(out)
